import {readFile, writeFile} from "node:fs/promises";
import {runtimeCatalog, validateRuntimeCatalog} from "../dist/runtime/catalog.js";

if (process.argv.slice(2).some(argument => argument !== "--check")) {
  throw new Error("Usage: node scripts/supported-platforms.mjs [--check]");
}

validateRuntimeCatalog();
const catalog = runtimeCatalog();
const cores = new Map(catalog.cores.map(core => [core.id, core]));
const boundTargets = new Set(catalog.bindings.map(binding => `${binding.providerId}/${binding.targetId}`));
const targetCount = catalog.providers.reduce((total, provider) => total + provider.targets.length, 0);
const unbound = catalog.providers.flatMap(provider => provider.targets
  .filter(target => !boundTargets.has(`${provider.providerId}/${target.id}`))
  .map(target => [code(provider.providerId), `${target.displayName} (${code(target.id)})`, saveType(target)]));

const document = [
  "# Supported platforms and cores",
  "",
  "<!-- Generated by scripts/supported-platforms.mjs. Run npm run docs:platforms to update. -->",
  "",
  "This is the complete platform, core and Target catalog declared by this checkout of retrom-runtime. " +
    "On `master` it follows current development. To check an installed release, inspect the matching tag's " +
    "catalog sources or this page when available. " +
    "The host's installed runtime catalog determines the available integrations.",
  "",
  "Catalog membership describes an integration, not compatibility with every game. " +
    "Game formats, firmware, input and browser requirements depend on the selected Target. " +
    "The [Target guides](README.md#target-guides) describe specific restrictions; " +
    "[product acceptance records](acceptance/clean-refactor.md) retain the tested versions and evidence scope separately.",
  "",
  "## Catalog summary",
  "",
  table(["Item", "Count"], [
    ["Platforms (`platformId`)", catalog.platforms.length],
    ["Bound cores (`coreId`)", new Set(catalog.bindings.map(binding => binding.coreId)).size],
    ["Product bindings", catalog.bindings.length],
    ["Bound Provider Targets", boundTargets.size],
    ["Declared Provider Targets", targetCount],
  ]),
  "",
  table(["Provider", "Declared Targets", "Bound Targets"], catalog.providers.map(provider => [
    code(provider.providerId), provider.targets.length,
    provider.targets.filter(target => boundTargets.has(`${provider.providerId}/${target.id}`)).length,
  ])),
  "",
  "A platform is a hardware system or game-engine family. A `coreId` is the host-selectable core identity. " +
    "A Target is identified by `providerId + targetId` and declares the actual runtime capabilities. " +
    "A binding connects a core and its platforms/content kinds to one Target. These counts differ because " +
    "one core can serve several platforms or Targets: RPG Maker has separate engine Targets, while " +
    "Genesis Plus GX separates cartridge and CD execution.",
  "",
  "## Platforms and available cores",
  "",
  "Every core listed below has a product binding for that platform. Entries are sorted by `platformId`.",
  "",
  table(["Platform", "Available cores (`coreId`)"], [...catalog.platforms].sort(byId).map(platform => [
    `${platform.displayName} (${code(platform.id)})`,
    [...new Set(catalog.bindings.filter(binding => binding.platformIds.includes(platform.id))
      .map(binding => binding.coreId))].sort(compare).map(coreName).join("; "),
  ])),
  "",
  "## Bound Targets and save types",
  "",
  "`INSTANT` restores an execution-state checkpoint in a new instance. " +
    "`GAME_SAVE` transfers game-native save data and may require saving/loading through the game's menus. " +
    "`NO_SAVE` means the Target offers no checkpoint. These are declared semantics; " +
    "the acceptance records establish which game scenarios have actually been verified.",
  "",
  "The Content column lists the accepted content kind and, where present, the required RPG Maker engine. " +
    "Use the Target guides for file extensions and project layout; a project content kind does not accept arbitrary directories.",
  "",
  ...catalog.providers.flatMap(provider => [
    `### ${provider.providerId}`,
    "",
    table(["Core (`coreId`)", "Target (`targetId`)", "Platforms", "Content", "Save type"],
      catalog.bindings.filter(binding => binding.providerId === provider.providerId).sort((a, b) => compare(a.targetId, b.targetId))
        .map(binding => {
          const target = provider.targets.find(target => target.id === binding.targetId);
          return [coreName(binding.coreId), `${target.displayName} (${code(target.id)})`,
            binding.platformIds.map(code).join(", "),
            [...binding.contentKinds, ...(binding.engine ? [binding.engine] : [])].map(code).join(" / "), saveType(target)];
        })),
    "",
  ]),
  "## Targets without a product binding",
  "",
  "These Targets are declared by a Provider but have no corresponding entry in the product binding catalog. " +
    "Their declaration alone does not add a host-selectable core or platform.",
  "",
  unbound.length ? table(["Provider", "Target (`targetId`)", "Save type"], unbound) : "None.",
  "",
  "## Sources and maintenance",
  "",
  "This page is generated from [`runtimeCatalog()`](../src/runtime/catalog.ts). " +
    "The machine-readable sources are [platform names](../src/runtime/platforms.json), " +
    "[core names](../src/runtime/core-names.json), [product bindings](../src/runtime/bindings.json), " +
    "and the [EmulatorJS](../src/providers/emulatorjs/catalog.ts) / " +
    "[native Web/Wasm](../src/providers/retrom-runtime/catalog.ts) Provider declarations. " +
    "The acceptance matrix is a versioned evidence snapshot, not the current support inventory.",
  "",
  "After changing these sources, regenerate and commit this page with the change:",
  "",
  "```bash",
  "npm ci",
  "npm run docs:platforms",
  "npm run docs:platforms:check",
  "```",
  "",
  "Both documentation commands compile the current runtime source before reading the catalog. " +
    "They do not download or build third-party cores or Provider archives. " +
    "The quality workflow checks that this page matches the catalog. Edit the generator for prose or layout changes.",
  "",
].join("\n");

const output = new URL("../docs/supported-platforms-and-cores.md", import.meta.url);
if (process.argv.includes("--check")) {
  const current = await readFile(output, "utf8").catch(error => {
    if (error.code === "ENOENT") {return "";}
    throw error;
  });
  if (current !== document) {
    console.error("Supported platform documentation is out of date. Run npm run docs:platforms.");
    process.exitCode = 1;
  } else {console.log("supported-platforms: documentation matches the runtime catalog");}
} else {
  await writeFile(output, document);
  console.log(`supported-platforms: wrote ${catalog.platforms.length} platforms and ${targetCount} Targets`);
}

function code(value) {return `\`${value}\``;}
function compare(left, right) {return left < right ? -1 : left > right ? 1 : 0;}
function byId(left, right) {return compare(left.id, right.id);}
function coreName(id) {return `${cores.get(id).displayName} (${code(id)})`;}
function saveType(target) {return code(target.checkpoint?.semantics ?? "NO_SAVE");}
function table(headers, rows) {
  return [headers, headers.map(() => "---"), ...rows]
    .map(row => `| ${row.map(cell => String(cell).replaceAll("|", "\\|")).join(" | ")} |`).join("\n");
}
