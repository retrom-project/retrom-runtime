// @vitest-environment node
import {afterEach, expect, it, vi} from "vitest";
import {ContentIOError} from "./errors.js";
import {BlockPool, type BlockLoader, type BlockObject} from "./block-pool.js";
import {blockRange} from "./http.js";
import {NetworkWait, transientNetworkError, type ContentNetworkState} from "./network-wait.js";
import {RangeReader} from "./range-reader.js";
import {BLOCK_BYTES as B} from "./source.js";
const pools: BlockPool[] = [];
const byteAt = (n: number) => (n * 7 + 3) & 255;
const object = (): BlockObject => ({key: "game", state: {generation: "g1", pinnedEtag: null, revoked: false},
  source: {identity: {kind: "FILE_SHA256", sha256: "a".repeat(64)}, sizeBytes: 2 * B, url: "https://example.test/game",
    purpose: "GAME", transport: "RANGE_REQUIRED", etagPolicy: "EXPECTED_SHA256", contentLengthPolicy: "EXACT_IF_PRESENT"}});
/** The first `failures` loads fail with `error`; later loads return the generated bytes. */
function failing(failures: number, error: () => Error) {
  let calls = 0;
  const loader: BlockLoader = async (target, index) => {
    if (calls++ < failures) {throw error();}
    const {start, length} = blockRange(target.source, index);
    return Uint8Array.from({length}, (_, n) => byteAt(start + n));
  };
  return vi.fn(loader);
}
function setup(loader: BlockLoader, online?: (listener: () => void) => () => void) {
  const pool = new BlockPool(0, loader); pools.push(pool);
  const states: ContentNetworkState[] = [], waits: number[] = [];
  const network = new NetworkWait(state => states.push(state), {
    // A macrotask per wait, as with a real timer, so an endless outage cannot starve the test's own timers.
    wait: async (ms, signal) => {waits.push(ms); signal?.throwIfAborted(); await new Promise(resolve => setTimeout(resolve, 1));},
    online: online ?? (() => () => {}),
  });
  const reader = new RangeReader("one", object(), pool, undefined, undefined, network);
  return {reader, states, waits, network};
}
afterEach(() => {for (const pool of pools.splice(0)) {pool.close();}});

it("[NET-01] UNIT/a read that times out waits for the network and completes instead of failing", async () => {
  const load = failing(2, () => new ContentIOError("TIMEOUT"));
  const {reader, states, waits} = setup(load);
  const bytes = new Uint8Array(100);
  await expect(reader.readInto(B - 50, bytes)).resolves.toBe(100);
  expect([...bytes]).toEqual(Array.from({length: 100}, (_, n) => byteAt(B - 50 + n)));
  expect(states).toEqual(["WAITING", "RESTORED"]);
  expect(waits).toEqual([1000, 2000]);
  expect(load).toHaveBeenCalledTimes(4);
});

it("[NET-02] UNIT/network failures wait too, but content and authorization errors still fail at once", async () => {
  const network = setup(failing(1, () => new ContentIOError("NETWORK_FAILED", {retryable: true})));
  await expect(network.reader.readInto(0, new Uint8Array(10))).resolves.toBe(10);
  expect(network.states).toEqual(["WAITING", "RESTORED"]);
  for (const name of ["IDENTITY_CHANGED", "AUTHORIZATION_FAILED", "RANGE_INVALID"] as const) {
    const fatal = setup(failing(1, () => new ContentIOError(name)));
    await expect(fatal.reader.readInto(0, new Uint8Array(10))).rejects.toMatchObject({code: `CONTENT_IO_${name}`});
    expect(fatal.states).toEqual([]);
  }
  expect(transientNetworkError(new ContentIOError("TIMEOUT", {scope: "OBJECT"}))).toBe(false);
  expect(transientNetworkError(new Error("TIMEOUT"))).toBe(false);
});

it("[NET-03] UNIT/cancelling or closing during a network wait ends the read without reporting recovery", async () => {
  const {reader, states, network} = setup(failing(Number.MAX_SAFE_INTEGER, () => new ContentIOError("TIMEOUT")));
  const controller = new AbortController();
  const pending = reader.readInto(0, new Uint8Array(10), controller.signal);
  await vi.waitFor(() => expect(states).toEqual(["WAITING"]));
  controller.abort(new ContentIOError("ABORTED"));
  await expect(pending).rejects.toMatchObject({code: "CONTENT_IO_ABORTED"});
  expect(network.state).toBe("WAITING"); expect(states).toEqual(["WAITING"]);
  const closing = reader.readInto(0, new Uint8Array(10));
  await reader.close(); await expect(closing).rejects.toBeInstanceOf(Error);
  expect(states).toEqual(["WAITING"]);
});

it("[NET-04] UNIT/an online event ends the current backoff early", async () => {
  let fire: (() => void) | undefined;
  const network = new NetworkWait(() => {}, {
    wait: (_ms, signal) => new Promise(resolve => signal?.addEventListener("abort", () => resolve(), {once: true})),
    online: listener => {fire = listener; return () => {fire = undefined;};},
  });
  const waiting = network.wait({}, 3);
  await vi.waitFor(() => expect(fire).toBeTypeOf("function"));
  fire!(); await expect(waiting).resolves.toBeUndefined(); expect(fire).toBeUndefined();
});

it("[NET-05] UNIT/recovery is reported once, after every waiting read has succeeded", () => {
  const states: ContentNetworkState[] = [];
  const network = new NetworkWait(state => states.push(state));
  const first = {}, second = {};
  network.enter(first); network.enter(second); network.enter(first);
  network.leave(first, true); expect(states).toEqual(["WAITING"]);
  network.leave(second, true); expect(states).toEqual(["WAITING", "RESTORED"]);
  network.leave(second, true); expect(states).toEqual(["WAITING", "RESTORED"]);
});
