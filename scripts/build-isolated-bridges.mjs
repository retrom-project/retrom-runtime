import {build} from "esbuild";
import {readFile, writeFile} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import {resolve} from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
export async function buildIsolatedBridges(check = false) {
  for (const [name, installer] of [["native", "installRpgRuntimeNativeBridge"], ["tyranoscript", "installTyranoScriptBridge"]]) {
    const result = await build({absWorkingDir: root, stdin: {contents:
      `import {createIsolatedInputFilter} from './src/provider/isolated-input.ts';\n` +
      `import {${installer}} from './assets/runtime/${name}/bridge-source.js';\n` +
      `${installer}(window, createIsolatedInputFilter(window));\n`, resolveDir: root},
    bundle: true, format: "iife", platform: "browser", target: "es2022", write: false, minifySyntax: true, legalComments: "none"});
    const output = resolve(root, `assets/runtime/${name}/bridge.js`);
    const text = `// Generated by scripts/build-isolated-bridges.mjs.\n${result.outputFiles[0].text}`;
    if (check) {
      if (await readFile(output, "utf8") !== text) {throw new Error(`ISOLATED_BRIDGE_OUTDATED:${name}`);}
    } else {await writeFile(output, text);}
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildIsolatedBridges(process.argv.includes("--check"));
}
