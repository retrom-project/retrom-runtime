/** Synthetic section decoder: different constants, table order and section name. */
export function sectionDecoderFixture() {
  const b = fixture(), plain = Buffer.from(b), loader = 0x5800;
  const imm = (value: number) => {const q = Buffer.alloc(4); q.writeUInt32LE(value >>> 0); return [...q];};
  const va = (off: number) => 0x10000000 + (off < 0x2400 ? off + 0xc00 : off < 0x5400 ? off + 0x1c00 : off + 0x2800);
  const put = (at: number, bytes: number[]) => b.set(bytes, at);
  b.writeUInt16LE(3, 0x86); b.writeUInt32LE(0x9000, 0xd0);
  b.fill(0, 0x178, 0x180); b.write(".binn", 0x178); b.writeUInt32LE(0x1ff3, 0x180);
  b.write(".loader", 0x1c8); b.writeUInt32LE(0x600, 0x1d0); b.writeUInt32LE(0x8000, 0x1d4);
  b.writeUInt32LE(0x600, 0x1d8); b.writeUInt32LE(loader, 0x1dc); b.writeUInt32LE(0x60000020, 0x1ec);
  // The name scan and mapped section fields establish which bytes the loop owns.
  put(loader, [0x33, 0xc0, 0xb3, 105, 0xb2, 110, 0x80, 0x3c, 8, 46, 0x75, 25,
    0x80, 0x7c, 8, 1, 98, 0x75, 18, 0x38, 0x5c, 8, 2, 0x75, 12,
    0x38, 0x54, 8, 3, 0x75, 6, 0x38, 0x54, 8, 4, 0x74, 8, 0x40,
    0x3d, 0, 4, 0, 0, 0x72, 0xd9, 0x3d, 0, 4, 0, 0, 0x0f, 0x84, ...imm(0x16d),
    0x8b, 0x74, 8, 12, 0x8b, 0x54, 8, 8, 3, 0xf1, 0xbd, ...imm(va(0x600)),
    0x2b, 0xee, 0x0f, 0x88, ...imm(0x160), 0x3b, 0xea, 0x0f, 0x8f, ...imm(0x158),
    0x33, 0xc0, 0x57, 0x85, 0xd2, 0xbf, ...imm(0xa1b2c3d4), 0x0f, 0x86, ...imm(0x88)]);
  // 3*4 - 1, then *5*9*2 - 1 => multiplier 989. No game-derived constants.
  const recurrence = loader + 0x67, shared = loader + 0xd6;
  put(recurrence, [0x8d, 0x0c, 0x7f, 0xc1, 0xe1, 2, 0x2b, 0xcf, 0x8d, 0x0c, 0x89,
    0x8d, 0x0c, 0xc9, 0xd1, 0xe1, 0x2b, 0xcf, 0x81, 0xc1, ...imm(0x3579),
    0xc1, 0xef, 5, 0x33, 0xf9, 0x8b, 0xcf, 0x83, 0xe1, 3, 0x83, 0xf9, 3, 0x77, 0x4d,
    0xff, 0x24, 0x8d, ...imm(va(loader + 0x300))]);
  const cases = [loader + 0xb5, loader + 0x95, loader + 0xa6, loader + 0xc5];
  const bodies = [[0x80, 0xe3, 15, 0xc0, 0xe3, 4, 0xc0, 0xe9, 4],
    [0x80, 0xe1, 0x55, 0xd0, 0xeb, 0x80, 0xe3, 0x55, 0xd0, 0xe1],
    [0x80, 0xe3, 0x7f, 0xd0, 0xe3, 0xc0, 0xe9, 7],
    [0x80, 0xe1, 0x33, 0xc0, 0xeb, 2, 0x80, 0xe3, 0x33, 0xc0, 0xe1, 2]];
  for (let i = 0; i < cases.length; i++) {
    const at = cases[i], bytes = [0x8a, 0x0c, 0x30, 0x8a, 0xd9, ...bodies[i]];
    if (at + bytes.length !== shared) {bytes.push(0xeb, shared - at - bytes.length - 2);}
    put(at, bytes);
  }
  const order = [3, 0, 2, 1];
  order.forEach((value, i) => b.writeUInt32LE(va(cases[value]), loader + 0x300 + i * 4));
  put(shared, [2, 0xd9, 0x88, 0x1c, 0x30, 0x3b, 0xc5, 0x75, 7, 0x8a, 0x0c, 0x30,
    0x88, 0x4c, 0x24, 0x13, 0x40, 0x3b, 0xc2, 0x0f, 0x82, ...imm(recurrence - shared - 25)]);
  b[loader + 0x1a4] = b[loader + 0x1b4] = b[loader + 0x1b7] = 0xc3;
  const transform = (value: number, kind: number) => [((value & 15) << 4) | (value >>> 4),
    ((value & 0x55) << 1) | ((value >>> 1) & 0x55), ((value << 1) | (value >>> 7)) & 255,
    ((value & 0x33) << 2) | ((value >>> 2) & 0x33)][kind];
  const inverse = order.map(kind => {const table = new Uint8Array(256); for (let v = 0; v < 256; v++) {table[transform(v, kind)] = v;} return table;});
  let state = 0xa1b2c3d4;
  for (let at = 0x400; at < 0x400 + 0x1ff3; at++) {
    state = ((Math.imul(state, 989) + 0x3579) ^ (state >>> 5)) >>> 0;
    b[at] = inverse[state & 3][plain[at]];
  }
  return b;
}
